  ! Precompute per-depth Stark widths and shifts of all tabulated He I lines from the
  ! electron, proton, and He II number densities, and set table wavelengths in the run
  ! wavelength convention; call after the model atmosphere and EOS results are available,
  ! before any XlineSetup call (the arrays are shared read-only state in OpenMP regions)
  SUBROUTINE HeStarkInit

    INTEGER :: itau, k, j
    REAL(8) :: Tlg, w0, w1, w2, Xne, Xnp, Xnhe2, Gam

    IF (.NOT. ALLOCATED(HeGam)) ALLOCATE(HeGam(Ntau, NheTab), HeShf(Ntau, NheTab))

    ! table wavelengths in the run wavelength convention
    WlcHeRun = WlcHe
    IF (Wvac) WlcHeRun = Air2Vac(WlcHe)

    DO itau = 1, Ntau
      Tlg = LOG10(Atmos(itau)%T)
      Xne = Atmos(itau)%Xne
      Xnp = REAL(Fraction(IdxSpc(Ix%H2), itau), 8)
      Xnhe2 = REAL(Fraction(IdxSpc(Ix%He2), itau), 8)

      ! DS90 entries: electron, proton, and He II perturbers on the 6-knot grid
      CALL LagWt3(Tt90, Tlg, j, w0, w1, w2)
      DO k = 1, NheDS90
        Gam = ((w0 * We90(j,k) + w1 * We90(j-1,k) + w2 * We90(j-2,k)) * Xne + &
               (w0 * Wp90(j,k) + w1 * Wp90(j-1,k) + w2 * Wp90(j-2,k)) * Xnp + &
               (w0 * Wh90(j,k) + w1 * Wh90(j-1,k) + w2 * Wh90(j-2,k)) * Xnhe2) &
              * HeGamCnv / WlcHe(k)**2
        HeGam(itau,k) = MAX(Gam, 0d0)
        HeShf(itau,k) = ((w0 * Se90(j,k) + w1 * Se90(j-1,k) + w2 * Se90(j-2,k)) * Xne + &
                         (w0 * Sp90(j,k) + w1 * Sp90(j-1,k) + w2 * Sp90(j-2,k)) * Xnp + &
                         (w0 * Sh90(j,k) + w1 * Sh90(j-1,k) + w2 * Sh90(j-2,k)) * Xnhe2) * 1d-16
      END DO

      ! DS84 entries: electron and proton perturbers on the 4-knot grid
      CALL LagWt3(Tt84, Tlg, j, w0, w1, w2)
      DO k = 1, NheDS84
        Gam = ((w0 * We84(j,k) + w1 * We84(j-1,k) + w2 * We84(j-2,k)) * Xne + &
               (w0 * Wp84(j,k) + w1 * Wp84(j-1,k) + w2 * Wp84(j-2,k)) * Xnp) &
              * HeGamCnv / WlcHe(NheDS90+k)**2
        HeGam(itau,NheDS90+k) = MAX(Gam, 0d0)
        HeShf(itau,NheDS90+k) = ((w0 * Se84(j,k) + w1 * Se84(j-1,k) + w2 * Se84(j-2,k)) * Xne + &
                                 (w0 * Sp84(j,k) + w1 * Sp84(j-1,k) + w2 * Sp84(j-2,k)) * Xnp) * 1d-16
      END DO
    END DO

  END SUBROUTINE HeStarkInit

  ! Table entry matching a given central wavelength within HeMatchTol and lower level
  ! energy within HeEloTol; 0 if no match. WaveL must be in the run wavelength
  ! convention (air or vacuum); the energy test rejects chance wavelength coincidences
  ! with lines of other transitions
  PURE INTEGER FUNCTION HeMatchIdx(WaveL, Elo)

    REAL(8), INTENT(IN) :: WaveL, Elo
    INTEGER :: k

    HeMatchIdx = 0
    DO k = 1, NheTab
      IF (ABS(WaveL - WlcHeRun(k)) <= HeMatchTol .AND. ABS(Elo - EloHe(k)) <= HeEloTol) THEN
        HeMatchIdx = k
        RETURN
      END IF
    END DO

  END FUNCTION HeMatchIdx

  ! Three-point Lagrange interpolation weights on knot grid Tt at abscissa Tlg:
  ! selects knot j (3 <= j <= SIZE(Tt)) such that the interpolated value is
  ! w0*F(j) + w1*F(j-1) + w2*F(j-2), extrapolating beyond the grid ends
  PURE SUBROUTINE LagWt3(Tt, Tlg, j, w0, w1, w2)

    REAL(8), INTENT(IN) :: Tt(:), Tlg
    INTEGER, INTENT(OUT) :: j
    REAL(8), INTENT(OUT) :: w0, w1, w2
    INTEGER :: it
    REAL(8) :: Tj

    j = SIZE(Tt)
    DO it = 3, SIZE(Tt)
      IF (Tt(it) > Tlg) THEN
        j = it
        EXIT
      END IF
    END DO

    Tj = (Tt(j) - Tt(j-1)) * (Tt(j) - Tt(j-2)) * (Tt(j-1) - Tt(j-2))
    w0 = (Tlg - Tt(j-2)) * (Tlg   - Tt(j-1)) * (Tt(j-1) - Tt(j-2)) / Tj
    w1 = (Tlg - Tt(j-2)) * (Tt(j) - Tlg    ) * (Tt(j)   - Tt(j-2)) / Tj
    w2 = (Tlg - Tt(j-1)) * (Tlg   - Tt(j)  ) * (Tt(j)   - Tt(j-1)) / Tj

  END SUBROUTINE LagWt3

